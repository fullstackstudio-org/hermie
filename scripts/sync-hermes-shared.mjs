#!/usr/bin/env node
// Vendors the pure-TypeScript parts of NousResearch/hermes-agent `apps/shared`
// into packages/hermes-shared at the commit pinned in
// packages/hermes-shared/upstream.json.
//
//   node scripts/sync-hermes-shared.mjs          refresh the vendored copy
//   node scripts/sync-hermes-shared.mjs --check  fail if the tree has drifted
//
// Every rewrite below is asserted. A pattern that stops matching means upstream
// moved the code we depend on, and that must surface as a loud failure here
// rather than as a silently unpatched file three milestones later.

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = resolve(here, '../packages/hermes-shared')
const manifestPath = join(packageRoot, 'upstream.json')
const outDir = join(packageRoot, 'src')
const check = process.argv.includes('--check')

// index.ts is written by hand (the barrel); everything else in src/ is vendored.
const HAND_WRITTEN = new Set(['index.ts'])

class SyncError extends Error {}

/** A rewrite that must match, or the sync fails. */
const required = (name, apply) => ({ name, optional: false, apply })
/** A rewrite that may find nothing to do in a given file. */
const optional = (name, apply) => ({ name, optional: true, apply })

/**
 * Upstream writes relative specifiers with an explicit `.js` extension (NodeNext
 * habit). Metro and `moduleResolution: Bundler` both want them extensionless,
 * and rewriting is cheaper than teaching every consumer about the mismatch.
 */
const dropRelativeJsExtensions = optional('relative .js specifiers', source => {
  const pattern = /(\bfrom\s*|\bimport\s*\(\s*)(['"])(\.\.?\/[^'"]+)\.js\2/g
  const next = source.replace(pattern, (_match, lead, quote, specifier) => `${lead}${quote}${specifier}${quote}`)

  return { source: next, matched: next !== source }
})

const UPSTREAM_READ_WINDOW_LOCATION = `function readWindowLocation(): { host: string; protocol: string } {
  if (typeof window === 'undefined') {
    return { host: '', protocol: 'http:' }
  }

  return { host: window.location.host, protocol: window.location.protocol }
}`

const HERMIE_READ_WINDOW_LOCATION = `function readWindowLocation(): { host: string; protocol: string } {
  // Hermie rewrite (scripts/sync-hermes-shared.mjs): React Native defines a
  // \`window\` object but gives it no \`location\`, so upstream's \`typeof window\`
  // guard passes and the next line throws. Read \`globalThis.location\` instead
  // and accept it only when it carries the two strings this helper needs.
  const runtimeLocation = (globalThis as { location?: { host?: unknown; protocol?: unknown } }).location

  if (typeof runtimeLocation?.host === 'string' && typeof runtimeLocation.protocol === 'string') {
    return { host: runtimeLocation.host, protocol: runtimeLocation.protocol }
  }

  // No browser location: callers must pass \`host\`/\`protocol\` explicitly. The
  // https default keeps an accidental bare call on wss:// rather than ws://.
  return { host: '', protocol: 'https:' }
}`

const guardWindowLocation = required('readWindowLocation guard', source => {
  if (!source.includes(UPSTREAM_READ_WINDOW_LOCATION)) {
    return { source, matched: false }
  }

  return { source: source.replace(UPSTREAM_READ_WINDOW_LOCATION, HERMIE_READ_WINDOW_LOCATION), matched: true }
})

/** file name -> rewrites applied on top of the ones every file gets. */
const PER_FILE_REWRITES = {
  'websocket-url.ts': [guardWindowLocation]
}

const COMMON_REWRITES = [dropRelativeJsExtensions]

function banner(file, manifest) {
  return [
    `// Vendored from ${manifest.repo} ${manifest.sourceDir}/${file} @ ${manifest.commit} (${manifest.license}).`,
    '// Generated by scripts/sync-hermes-shared.mjs — do not edit by hand.',
    ''
  ].join('\n')
}

function rewriteFile(file, raw, manifest) {
  let source = raw
  const applied = []

  for (const rewrite of [...COMMON_REWRITES, ...(PER_FILE_REWRITES[file] ?? [])]) {
    const result = rewrite.apply(source)

    if (!result.matched && !rewrite.optional) {
      throw new SyncError(
        `${file}: required rewrite "${rewrite.name}" found nothing to change. ` +
          'Upstream moved the code this client depends on — re-read the file before bumping the pin.'
      )
    }

    if (result.matched) {
      applied.push(rewrite.name)
    }

    source = result.source
  }

  return { source: `${banner(file, manifest)}${source}`, applied }
}

async function fetchFile(file, manifest) {
  const url = `${manifest.rawBaseUrl}/${manifest.repo}/${manifest.commit}/${manifest.sourceDir}/${file}`
  // The raw host rate-limits shared CI runners now and then; a 429 or a 5xx
  // says nothing about the pin, so wait and ask again before failing the check.
  const waits = [2_000, 5_000, 15_000, 30_000]

  for (let attempt = 0; ; attempt += 1) {
    const response = await fetch(url)

    if (response.ok) {
      return response.text()
    }

    const retryable = response.status === 429 || response.status >= 500

    if (!retryable || attempt >= waits.length) {
      throw new SyncError(`${file}: ${response.status} ${response.statusText} from ${url}`)
    }

    await new Promise(resolve => setTimeout(resolve, waits[attempt]))
  }
}

async function readManifest() {
  if (!existsSync(manifestPath)) {
    throw new SyncError(`${manifestPath} is missing; it carries the pin and the file list.`)
  }

  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))

  for (const key of ['repo', 'commit', 'sourceDir', 'rawBaseUrl', 'license', 'files']) {
    if (!manifest[key]) {
      throw new SyncError(`upstream.json is missing "${key}".`)
    }
  }

  return manifest
}

async function main() {
  const manifest = await readManifest()
  const rendered = new Map()

  for (const file of manifest.files) {
    const raw = await fetchFile(file, manifest)
    const { source, applied } = rewriteFile(file, raw, manifest)
    rendered.set(file, source)

    if (!check) {
      console.log(`  ${file}${applied.length ? ` (${applied.join(', ')})` : ''}`)
    }
  }

  if (check) {
    const drift = []

    for (const [file, source] of rendered) {
      const path = join(outDir, file)
      const onDisk = existsSync(path) ? await readFile(path, 'utf8') : null

      if (onDisk === null) {
        drift.push(`${file}: missing from packages/hermes-shared/src`)
      } else if (onDisk !== source) {
        drift.push(`${file}: differs from the pinned upstream copy`)
      }
    }

    const present = existsSync(outDir) ? await readdir(outDir) : []

    for (const entry of present) {
      if (!HAND_WRITTEN.has(entry) && !rendered.has(entry)) {
        drift.push(`${entry}: not in upstream.json but present on disk`)
      }
    }

    if (drift.length > 0) {
      console.error('packages/hermes-shared/src has drifted from the pinned upstream commit:')

      for (const line of drift) {
        console.error(`  - ${line}`)
      }

      console.error('\nRun `npm run sync:hermes-shared` and commit the result.')
      process.exit(1)
    }

    console.log(`packages/hermes-shared/src matches ${manifest.repo}@${manifest.commit.slice(0, 12)}.`)

    return
  }

  await mkdir(outDir, { recursive: true })

  for (const entry of existsSync(outDir) ? await readdir(outDir) : []) {
    if (!HAND_WRITTEN.has(entry) && !rendered.has(entry)) {
      await rm(join(outDir, entry), { recursive: true, force: true })
      console.log(`  removed ${entry} (no longer in upstream.json)`)
    }
  }

  for (const [file, source] of rendered) {
    await writeFile(join(outDir, file), source, 'utf8')
  }

  console.log(`\nVendored ${rendered.size} files from ${manifest.repo}@${manifest.commit.slice(0, 12)}.`)
}

main().catch(error => {
  console.error(error instanceof SyncError ? error.message : error)
  process.exit(1)
})
